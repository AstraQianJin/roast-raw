class QuestionnaireAPITests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix='roast-raw-questionnaire-')
        self.addCleanup(temporary.cleanup)
        self.db_path = Path(temporary.name) / 'test.sqlite3'
        with patch.dict(os.environ, {'RR_DB_PATH': str(self.db_path)}):
            from server.app.main import create_app
            self.app = create_app(db_path=self.db_path, plan_path=PLAN_PATH)
        self.client = TestClient(self.app, raise_server_exceptions=False)
        self.client.__enter__()
        self.addCleanup(self.client.__exit__, None, None, None)
        self.seed = json.loads(PLAN_PATH.read_text(encoding='utf-8'))
        self.cycle_id = self.seed['meta']['planId']
        self.movement_ids = {row['movementId'] for row in self.seed['workouts']}

    def payload(self):
        payload = complete_competition_payload()
        first = next(iter(self.movement_ids))
        payload['outlook']['keepMovements'] = [first]
        return payload

    def put(self, status, payload, cycle_id=None):
        return self.client.put('/api/questionnaire', json={
            'cycle_id': cycle_id or self.cycle_id, 'status': status, 'payload': payload,
        })

    def test_get_empty_returns_null_skeleton(self):
        response = self.client.get('/api/questionnaire', params={'cycle_id': self.cycle_id})
        self.assertEqual(response.status_code, 200, response.text)
        body = response.json()
        self.assertEqual(body['status'], 'empty')
        self.assertIsNone(body['updated_at'])
        self.assertEqual(body['payload'], skeleton())

    def test_draft_save_round_trips_and_journals(self):
        response = self.put('draft', self.payload())
        self.assertEqual(response.status_code, 200, response.text)
        saved = response.json()
        self.assertEqual(saved['status'], 'draft')
        self.assertIsNotNone(saved['updated_at'])
        fetched = self.client.get('/api/questionnaire', params={'cycle_id': self.cycle_id}).json()
        self.assertEqual(fetched['payload']['personal']['age'], 30)
        self.assertEqual(fetched['payload']['schedule']['testDates'], ['2027-03-20'])
        import sqlite3
        with closing(sqlite3.connect(self.db_path)) as db:
            kinds = [row[0] for row in db.execute(
                "SELECT kind FROM records_journal WHERE cycle_id=?", (self.cycle_id,))]
        self.assertIn('questionnaire', kinds)

    def test_complete_requires_fields_with_422(self):
        response = self.put('complete', skeleton())
        self.assertEqual(response.status_code, 422, response.text)
        fields = {entry['field'] for entry in response.json()['errors']}
        self.assertIn('personal.age', fields)
        self.assertIn('level.sbd1rm.squat', fields)

    def test_invalid_value_is_422_not_silent_repair(self):
        payload = self.payload()
        payload['personal']['age'] = 9
        response = self.put('draft', payload)
        self.assertEqual(response.status_code, 422, response.text)
        self.assertIn('personal.age', {entry['field'] for entry in response.json()['errors']})
        fetched = self.client.get('/api/questionnaire', params={'cycle_id': self.cycle_id}).json()
        self.assertEqual(fetched['status'], 'empty', 'rejected save must not persist')

    def test_last_write_wins_replaces_previous_answer(self):
        first = self.payload()
        self.assertEqual(self.put('draft', first).status_code, 200)
        second = self.payload()
        second['personal']['age'] = 41
        self.assertEqual(self.put('draft', second).status_code, 200)
        fetched = self.client.get('/api/questionnaire', params={'cycle_id': self.cycle_id}).json()
        self.assertEqual(fetched['payload']['personal']['age'], 41)

    def test_complete_then_new_draft_replaces_record(self):
        self.assertEqual(self.put('complete', self.payload()).status_code, 200)
        self.assertEqual(self.put('draft', skeleton()).status_code, 200)
        fetched = self.client.get('/api/questionnaire', params={'cycle_id': self.cycle_id}).json()
        self.assertEqual(fetched['status'], 'draft')
        self.assertIsNone(fetched['payload']['personal']['age'])

    def test_archived_cycle_is_read_only(self):
        import sqlite3
        archived_id = self.cycle_id + '-archived'
        with closing(sqlite3.connect(self.db_path)) as db:
            account = db.execute('SELECT account_id FROM cycles LIMIT 1').fetchone()[0]
            db.execute("INSERT INTO cycles(account_id,id,name,start_date,end_date,status,schema_version) "
                       "VALUES(?,?,?,?,?,?,?)",
                       (account, archived_id, 'Archived', '2026-01-01', '2026-04-01', 'archived',
                        self.seed['schemaVersion']))
            db.execute("INSERT INTO plans(account_id,id,cycle_id,json,version,created_at) VALUES(?,?,?,?,?,?)",
                       (account, archived_id, archived_id, json.dumps(self.seed),
                        self.seed['schemaVersion'], '2026-01-01T00:00:00+00:00'))
            db.commit()
        response = self.put('draft', skeleton(), cycle_id=archived_id)
        self.assertEqual(response.status_code, 409, response.text)

    def test_questionnaire_is_part_of_review_source(self):
        self.assertEqual(self.put('complete', self.payload()).status_code, 200)
        review = self.client.get('/api/review', params={'cycle_id': self.cycle_id}).json()
        self.assertEqual(review['questionnaire']['status'], 'complete')
        self.assertEqual(review['questionnaire']['payload']['personal']['age'], 30)

    def test_questionnaire_save_invalidates_import_preview(self):
        candidate = copy.deepcopy(self.seed)
        candidate['meta']['planId'] = 'questionnaire-preview-invalidation'
        candidate_text = json.dumps(candidate)
        preview = self.client.post('/api/plan/import/preview',
                                   json={'plan_json': candidate_text, 'filename': 'b.json'})
        self.assertEqual(preview.status_code, 200, preview.text)
        stale = preview.json()
        self.assertEqual(self.put('draft', self.payload()).status_code, 200)
        confirm = self.client.post('/api/plan/import/confirm', json={
            'plan_json': candidate_text, 'filename': 'b.json',
            'current_id': stale['currentId'], 'candidate_id': stale['candidateId'],
            'confirm': True})
        self.assertEqual(confirm.status_code, 409,
                         'questionnaire save must change the review digest and block stale confirm')


class QuestionnaireMigrationTests(unittest.TestCase):
    def test_v3_to_v4_adds_table_snapshots_and_keeps_data(self):
        from server.app.store import Store
        temporary = tempfile.TemporaryDirectory(prefix='roast-raw-q-migration-')
        self.addCleanup(temporary.cleanup)
        path = Path(temporary.name) / 'test.sqlite3'
        store = Store(path)
        seed = json.loads(PLAN_PATH.read_text(encoding='utf-8'))
        store.initialize(seed)
        store.upgrade()
        store.upgrade_prescriptions()
        import sqlite3
        with closing(sqlite3.connect(path)) as db:
            self.assertEqual(db.execute('PRAGMA user_version').fetchone()[0], 3)
            before = db.execute('SELECT COUNT(*) FROM logs').fetchone()[0]
        store.upgrade_questionnaire()
        with closing(sqlite3.connect(path)) as db:
            self.assertEqual(db.execute('PRAGMA user_version').fetchone()[0], 4)
            self.assertEqual(db.execute('PRAGMA integrity_check').fetchone()[0], 'ok')
            tables = {row[0] for row in db.execute(
                "SELECT name FROM sqlite_master WHERE type='table'")}
            self.assertIn('questionnaires', tables)
            self.assertEqual(db.execute('SELECT COUNT(*) FROM logs').fetchone()[0], before)
        backups = list((path.parent / 'backups').glob('*.sqlite3'))
        self.assertTrue(backups, 'v4 migration must take a consistent snapshot')
        # Idempotent: a second call at v4 changes nothing.
        store.upgrade_questionnaire()
        with closing(sqlite3.connect(path)) as db:
            self.assertEqual(db.execute('PRAGMA user_version').fetchone()[0], 4)


