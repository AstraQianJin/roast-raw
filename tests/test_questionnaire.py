PLAN_PATH = ROOT / 'data' / 'plan.json'
MOVEMENT_IDS = {'S.Main|low-bar squat', 'B.Main|bench press', 'D.Main|sumo deadlift'}


def complete_competition_payload():
    """A minimal-but-complete competition answer, built from the null skeleton."""
    payload = skeleton()
    payload['goal']['type'] = 'competition'
    payload['schedule'].update({
        'startDate': '2026-11-16', 'competitionDate': '2027-03-20',
        'testDates': ['2027-03-20'], 'trainingDaysPerWeek': 4, 'sessionMinutes': 90,
    })
    payload['personal'].update({
        'age': 30, 'sex': 'male', 'heightCm': 175, 'bodyweightKg': 85,
        'trainingYears': 5, 'equipment': 'classic',
    })
    payload['level']['sbd1rm'] = {'squat': 180, 'bench': 120, 'deadlift': 220}
    payload['level']['oneRmSource'] = 'measured'
    payload['outlook'].update({
        'targetBodyweightKg': 84, 'riskPreference': 'steady', 'testGroups': ['sbd'],
    })
    return payload


def fields_of(error):
    return {entry['field'] for entry in error.errors}


class SkeletonTests(unittest.TestCase):
    def test_skeleton_is_null_and_carries_exact_variation_ids(self):
        payload = skeleton()
        self.assertEqual(payload['schemaVersion'], SCHEMA_VERSION)
        self.assertEqual(set(payload), {
            'schemaVersion', 'goal', 'schedule', 'personal', 'level',
            'limits', 'recovery', 'outlook', 'notes',
        })
        self.assertIsNone(payload['goal']['type'])
        self.assertIsNone(payload['personal']['age'])
        self.assertEqual(payload['schedule']['testDates'], [])
        self.assertEqual(set(payload['level']['variationPrs']), set(VARIATION_IDS))
        self.assertEqual(set(payload['outlook']['variationTargets']), set(VARIATION_IDS))
        self.assertEqual(len(VARIATION_IDS), 8)
        for value in payload['level']['variationPrs'].values():
            self.assertIsNone(value)

    def test_skeleton_is_a_valid_draft(self):
        validate_questionnaire(skeleton(), 'draft', MOVEMENT_IDS)

    def test_skeleton_is_not_complete(self):
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(skeleton(), 'complete', MOVEMENT_IDS)
        missing = fields_of(caught.exception)
        for field in ('goal.type', 'schedule.startDate', 'schedule.trainingDaysPerWeek',
                      'personal.age', 'personal.sex', 'personal.heightCm',
                      'personal.bodyweightKg', 'outlook.targetBodyweightKg',
                      'outlook.riskPreference', 'level.sbd1rm.squat',
                      'level.sbd1rm.bench', 'level.sbd1rm.deadlift'):
            self.assertIn(field, missing)


class ValidationTests(unittest.TestCase):
    def valid(self):
        return complete_competition_payload()

    def test_complete_competition_passes(self):
        validate_questionnaire(self.valid(), 'complete', MOVEMENT_IDS)

    def test_status_must_be_draft_or_complete(self):
        for status in ('published', '', None):
            with self.assertRaises(Reject):
                validate_questionnaire(skeleton(), status, MOVEMENT_IDS)

    def test_schema_version_is_exact(self):
        payload = self.valid()
        payload['schemaVersion'] = 'RR-Questionnaire-v2'
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
        self.assertIn('schemaVersion', fields_of(caught.exception))

    def test_unknown_section_and_field_are_rejected(self):
        payload = self.valid()
        payload['extraSection'] = {}
        payload['personal']['nickname'] = 'x'
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
        fields = fields_of(caught.exception)
        self.assertIn('extraSection', fields)
        self.assertIn('personal.nickname', fields)

    def test_boolean_is_not_a_number(self):
        payload = self.valid()
        payload['personal']['age'] = True
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
        self.assertIn('personal.age', fields_of(caught.exception))

    def test_nonfinite_numbers_are_rejected(self):
        payload = self.valid()
        payload['personal']['bodyweightKg'] = float('nan')
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
        self.assertIn('personal.bodyweightKg', fields_of(caught.exception))

    def test_out_of_range_values_are_rejected(self):
        cases = [
            ('personal', 'age', 9), ('personal', 'age', 101),
            ('schedule', 'trainingDaysPerWeek', 0), ('schedule', 'trainingDaysPerWeek', 7),
            ('schedule', 'sessionMinutes', 14), ('schedule', 'sessionMinutes', 241),
            ('personal', 'heightCm', 99), ('personal', 'bodyweightKg', 301),
            ('recovery', 'sleepQuality', 0), ('recovery', 'stressLevel', 6),
            ('outlook', 'targetBodyweightKg', 29), ('outlook', 'targetTotalKg', 1801),
        ]
        for section, field, value in cases:
            payload = self.valid()
            payload[section][field] = value
            with self.assertRaises(Reject, msg=f'{section}.{field}={value}') as caught:
                validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
            self.assertIn(f'{section}.{field}', fields_of(caught.exception))

    def test_integer_fields_reject_floats(self):
        payload = self.valid()
        payload['schedule']['trainingDaysPerWeek'] = 4.5
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
        self.assertIn('schedule.trainingDaysPerWeek', fields_of(caught.exception))

    def test_enum_values_are_closed(self):
        payload = self.valid()
        payload['personal']['sex'] = 'unknown'
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
        self.assertIn('personal.sex', fields_of(caught.exception))

    def test_dates_must_be_real_calendar_dates(self):
        payload = self.valid()
        payload['schedule']['startDate'] = '2026-02-30'
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
        self.assertIn('schedule.startDate', fields_of(caught.exception))
        payload = self.valid()
        payload['schedule']['startDate'] = '2026-13-01'
        with self.assertRaises(Reject):
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)

    def test_variation_keys_must_be_exactly_the_eight_ids(self):
        payload = self.valid()
        del payload['level']['variationPrs'][VARIATION_IDS[0]]
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
        self.assertIn('level.variationPrs', fields_of(caught.exception))
        payload = self.valid()
        payload['outlook']['variationTargets']['not-a-real-id'] = 100
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
        self.assertIn('outlook.variationTargets', fields_of(caught.exception))

    def test_sbd1rm_requires_all_three_lifts(self):
        payload = self.valid()
        del payload['level']['sbd1rm']['bench']
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
        self.assertIn('level.sbd1rm', fields_of(caught.exception))

    def test_competition_locks_test_dates_and_groups(self):
        payload = self.valid()
        payload['schedule']['testDates'] = ['2027-01-01']
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'complete', MOVEMENT_IDS)
        self.assertIn('schedule.testDates', fields_of(caught.exception))
        payload = self.valid()
        payload['outlook']['testGroups'] = ['sbd', 'five-km']
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'complete', MOVEMENT_IDS)
