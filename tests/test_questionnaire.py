    def test_tri_state_recovery_must_be_boolean_or_null(self):
        payload = self.valid()
        payload['recovery']['proteinSufficient'] = 'yes'
        with self.assertRaises(Reject) as caught:
            validate_questionnaire(payload, 'draft', MOVEMENT_IDS)
        self.assertIn('recovery.proteinSufficient', fields_of(caught.exception))
        payload = self.valid()
